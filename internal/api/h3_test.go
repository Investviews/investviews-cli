// A real cell must be accepted in BOTH documented forms and in either case,
// and all three spellings must parse to the same index — otherwise "accepted"
// means different things on the two routes into --h3.
func TestParseH3CellAcceptsRealCellsAtEveryResolution(t *testing.T) {
	for _, c := range realCellsByResolution {
		t.Run(c.canonical, func(t *testing.T) {
			if !IsH3Cell(c.decimal) {
				t.Fatalf("res %d %s (%s) is a real cell and must be accepted", c.res, c.canonical, c.place)
			}
			for _, form := range []string{
				strconv.FormatUint(c.decimal, 10),
				c.canonical,
				strings.ToUpper(c.canonical),
			} {
				got, err := ParseH3Cell(form)
				if err != nil {
					t.Fatalf("ParseH3Cell(%q) = %v, want the cell", form, err)
				}
				if got != c.decimal {
					t.Errorf("ParseH3Cell(%q) = %d, want %d", form, got, c.decimal)
				}
			}
		})
	}
}


// withField replaces one field of an index, leaving every other bit alone, so
// a rejection below can only be attributed to the field that moved.
func withField(index uint64, shift, mask, value uint64) uint64 {
	return (index &^ (mask << shift)) | ((value & mask) << shift)
}

// withDigit replaces digit r (1..15) of an index.
func withDigit(index uint64, r int, value uint64) uint64 {
	return withField(index, uint64((h3MaxRes-r)*h3DigitBits), h3DigitMask, value)
}

// ⚠️ ONE FAULT PER CASE, AND EACH CASE STATES WHICH CHECK IS SUPPOSED TO CATCH
// IT. The failure mode this guards against is a case that passes for the wrong
// reason — a "malformed" id that is really being refused by the mode test.
// That is why every row carries oldCheckWouldAccept: the rows marked true are
// exactly the ids that the mode-bits-only check LET THROUGH onto the metered
// endpoint, and if a future edit narrows the check back to the mode, those
// rows fail.
func TestIsH3CellRejectsEachStructuralFaultOnItsOwn(t *testing.T) {
	// Res 8, València — the whole table below is this one cell with one
	// field changed.
	const good = uint64(613498079194120191) // 8839540a8bfffff
	if !IsH3Cell(good) {
		t.Fatalf("the fixture cell %d must be accepted, or every case below proves nothing", good)
	}

	cases := []struct {
		name                string
		index               uint64
		oldCheckWouldAccept bool
	}{
		{"bit 63, the reserved high bit, is set", good | (1 << h3HighBitShift), false},
		{"mode 0 — an index that names nothing", withField(good, h3ModeShift, h3ModeMask, 0), false},
		{"mode 2 — a directed edge, not a cell", withField(good, h3ModeShift, h3ModeMask, 2), false},
		{"mode 15 — the top of the mode field", withField(good, h3ModeShift, h3ModeMask, 15), false},

		{"mode-dependent bits set to 1", withField(good, h3ReservedShift, h3ReservedMask, 1), true},
		{"mode-dependent bits set to 7", withField(good, h3ReservedShift, h3ReservedMask, 7), true},

		{"base cell 122 — one past the last one", withField(good, h3BaseCellShift, h3BaseCellMask, 122), true},
		{"base cell 127 — the top of the field", withField(good, h3BaseCellShift, h3BaseCellMask, 127), true},

		// Digits 9..15 are above res 8 and must all be 7.
		{"unused digit 15 is 6, not 7", withDigit(good, 15, 6), true},
		{"unused digit 15 is 0, not 7", withDigit(good, 15, 0), true},
		{"unused digit 9 is 0, not 7", withDigit(good, 9, 0), true},

		// Digits 1..8 are in use and 7 never names a direction.
		{"used digit 1 is 7", withDigit(good, 1, 7), true},
		{"used digit 8 is 7", withDigit(good, 8, 7), true},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if IsH3Cell(tc.index) {
				t.Fatalf("%d (%x) is malformed and must be refused", tc.index, tc.index)
			}
			oldCheck := tc.index>>h3ModeShift == h3CellMode
			if oldCheck != tc.oldCheckWouldAccept {
				t.Errorf("the mode-bits-only check accepted = %v, want %v — this case is no "+
					"longer testing what it says it tests", oldCheck, tc.oldCheckWouldAccept)
			}
			// And it must be refused through the string route too, in
			// both documented spellings.
			for _, form := range []string{
				strconv.FormatUint(tc.index, 10),
				strconv.FormatUint(tc.index, 16),
			} {
				if _, err := ParseH3Cell(form); err == nil {
					t.Errorf("ParseH3Cell(%q) accepted a malformed id", form)
				}
			}
		})
	}
}

// ⚠️ THE ID FROM THE REVIEW FINDING. 8839540ad1ffffe differs from the real
// cell 8839540ad1fffff in ONE bit: its last unused digit is 6 rather than 7.
// It parses as hex and carries the cell mode, so the mode-bits-only check sent
// it to the METERED endpoint and paid for a server 400.
//
// The neighbour is here because the point is a one-bit difference, not a
// blocklist: the real id must still be accepted.
func TestParseH3CellRejectsAWellFormedLookingIdWithABadUnusedDigit(t *testing.T) {
	const bad = "8839540ad1ffffe"
	const good = "8839540ad1fffff"

	index, err := strconv.ParseUint(bad, 16, 64)
	if err != nil {
		t.Fatalf("the finding's id must at least parse as hex: %v", err)
	}
	if index>>h3ModeShift != h3CellMode {
		t.Fatal("the finding's id carries the cell mode; without that it proves nothing")
	}
	if _, err := ParseH3Cell(bad); err == nil {
		t.Errorf("%s has a used-digit value in an unused slot and must be refused locally", bad)
	}
	if _, err := ParseH3Cell(good); err != nil {
		t.Errorf("%s is a real cell and must still be accepted: %v", good, err)
	}
}

// ⚠️ WHAT THE CHECK DELIBERATELY DOES NOT CATCH, pinned so it cannot be
// mistaken for an oversight. Base cell 4 is a pentagon, and on a pentagon the
// first non-zero digit may not be 1 — that path does not exist on the grid.
// Ruling it out needs the pentagon table, which is where a few bit tests would
// turn into an H3 implementation, so 830840fffffffff is accepted here and
// answered 400 by the server.
//
// The trade is one wasted request against the risk of wrongly refusing a real
// cell, which would break --h3 outright. If a later change adds the pentagon
// table, this test is the one to update — and h3.go, docs/api.md and
// skills/investviews/SKILL.md all describe the residue and would need it gone.
func TestIsH3CellAcceptsTheDocumentedPentagonResidue(t *testing.T) {
	const impossiblePentagonPath = "830840fffffffff" // pentagon base 4, digit 1 = 1
	const realNeighbour = "830880fffffffff"          // the same cell with digit 1 = 2

	if _, err := ParseH3Cell(impossiblePentagonPath); err != nil {
		t.Errorf("%s is structurally well formed; the documented behaviour is to accept it "+
			"and let the server refuse it: %v", impossiblePentagonPath, err)
	}
	if _, err := ParseH3Cell(realNeighbour); err != nil {
		t.Errorf("%s is a real cell: %v", realNeighbour, err)
	}
}
